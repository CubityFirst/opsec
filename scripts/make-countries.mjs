#!/usr/bin/env node
/**
 * Regenerates `src/shared/country-names.ts` from the ICU data Node ships with
 * (`npm run countries`). The hand-written bits — aliases, the flag helper, the
 * codes with no emoji flag — live next door in `src/shared/countries.ts` and are
 * never touched by this script.
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const LOCALE = "en-GB";
/** Deprecated codes ICU still answers for (they alias onto a current name) and groupings nobody is from. */
const SKIP = new Set(["AN", "BU", "CS", "DD", "DY", "EU", "EZ", "FX", "HV", "NH", "QO", "QU", "RH", "SU", "TP", "UK", "UN", "VD", "XA", "XB", "YD", "YU", "ZR", "ZZ"]);

const names = new Intl.DisplayNames([LOCALE], { type: "region" });
const letters = "ABCDEFGHIJKLMNOPQRSTUVWXYZ".split("");
const seen = new Set();
const entries = [];
for (const a of letters) {
  for (const b of letters) {
    const code = a + b;
    if (SKIP.has(code)) continue;
    let name;
    try {
      name = names.of(code);
    } catch {
      continue;
    }
    if (!name || name === code || seen.has(name)) continue;
    seen.add(name);
    entries.push([code, name]);
  }
}
entries.sort((x, y) => x[1].localeCompare(y[1], "en"));

const file = `// Generated by scripts/make-countries.mjs (npm run countries) — do not edit by hand.
// ISO 3166-1 alpha-2 code → ICU ${LOCALE} name, territories included.
export const COUNTRY_NAMES: Record<string, string> = {
${entries.map(([code, name]) => `  ${code}: ${JSON.stringify(name)},`).join("\n")}
};
`;
writeFileSync(fileURLToPath(new URL("../src/shared/country-names.ts", import.meta.url)), file);
console.log(`${entries.length} countries`);
